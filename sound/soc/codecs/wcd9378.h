/*
 * WCD9378 (Tambora) SDCA register address model.
 * Registers are addressed as 32-bit values encoding:
 *   [31:24] = Function Number
 *   [23:16] = Entity Number
 *   [15:0]  = Control Number
 *
 * The base address 0x3fffffff is used as the SoundWire SDCA base.
 */
#define WCD9378_BASE			0x3fffffff

/* Helper: extract regmap index from SDCA address */
#define WCD9378_REG(reg)		(((reg & 0x0ff00000) >> 8) | (reg & 0xfff))

